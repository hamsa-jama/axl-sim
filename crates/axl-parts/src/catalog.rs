//! Loading and saving part files (`assets/parts/*.ron`) and the in-memory catalog.

use std::collections::BTreeMap;
use std::path::Path;

use crate::types::{PartDef, PartId};

/// Highest part file version this build understands.
pub const PART_FILE_VERSION: u32 = 1;

/// Problems loading a part.
#[derive(Debug, thiserror::Error)]
pub enum PartsError {
    /// A file or folder could not be read.
    #[error("could not read {path}: {message}")]
    Io {
        /// Path.
        path: String,
        /// Message.
        message: String,
    },
    /// A file is not valid part RON.
    #[error("could not parse {path}: {message}")]
    Parse {
        /// Path.
        path: String,
        /// Message.
        message: String,
    },
    /// A file was written by a newer AXL.
    #[error("This file was made by a newer version of AXL.")]
    TooNew,
    /// A part breaks a catalog rule.
    #[error("part {id}: {problem}")]
    Invalid {
        /// Part id.
        id: String,
        /// What is wrong.
        problem: String,
    },
}

/// Parse one part file.
pub fn parse_part(text: &str, path: &str) -> Result<PartDef, PartsError> {
    let def: PartDef = ron::de::from_str(text).map_err(|e| PartsError::Parse {
        path: path.into(),
        message: e.to_string(),
    })?;
    if def.version > PART_FILE_VERSION {
        return Err(PartsError::TooNew);
    }
    check(&def)?;
    Ok(def)
}

/// Catalog rules every part must satisfy.
pub fn check(def: &PartDef) -> Result<(), PartsError> {
    let bad = |problem: &str| PartsError::Invalid {
        id: def.id.0.clone(),
        problem: problem.into(),
    };
    if def.bodies.is_empty() || def.bodies.len() > 2 {
        return Err(bad("a part has one or two bodies"));
    }
    if def.bodies.len() == 2 && def.internal_joint.is_none() {
        return Err(bad("a part with two bodies needs an internal joint"));
    }
    if def.bodies.len() == 1 && def.internal_joint.is_some() {
        return Err(bad("an internal joint needs two bodies"));
    }
    for b in &def.bodies {
        if !(b.mass_kg > 0.0 && b.mass_kg.is_finite()) {
            return Err(bad("mass must be positive"));
        }
        if b.collision.is_empty() {
            return Err(bad("every body needs a collision shape"));
        }
    }
    if def.colors.is_empty() {
        return Err(bad("at least one colour"));
    }
    Ok(())
}

/// Serialise a part as pretty RON, with a header comment.
pub fn to_ron(def: &PartDef) -> String {
    let cfg = ron::ser::PrettyConfig::new()
        .depth_limit(8)
        .indentor("    ");
    let body = ron::ser::to_string_pretty(def, cfg).unwrap_or_default();
    format!(
        "// {} ({:?}). Lengths in metres, connector positions in 0.1 mm.\n// Generated by `cargo xtask gen-parts` from crates/axl-parts/src/generate.rs; change the generator, not this file.\n// Masses marked Placeholder are `placeholder: calibrate` (docs/calibration.md).\n{body}\n",
        def.name, def.category
    )
}

/// All parts, by id.
#[derive(Clone, Debug, Default)]
pub struct Catalog {
    parts: BTreeMap<PartId, PartDef>,
}

impl Catalog {
    /// The catalog built into the program (see [`crate::generate`]).
    pub fn builtin() -> Self {
        Self::from_defs(crate::generate::builtin_parts())
    }

    /// Build from a list of definitions.
    pub fn from_defs(defs: Vec<PartDef>) -> Self {
        Self {
            parts: defs.into_iter().map(|d| (d.id.clone(), d)).collect(),
        }
    }

    /// Load every `*.ron` file in `dir`. The file name must match the part id.
    pub fn load_dir(dir: &Path) -> Result<Self, PartsError> {
        let io = |e: std::io::Error, p: &Path| PartsError::Io {
            path: p.display().to_string(),
            message: e.to_string(),
        };
        let mut parts = BTreeMap::new();
        let mut paths: Vec<_> = std::fs::read_dir(dir)
            .map_err(|e| io(e, dir))?
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|x| x == "ron"))
            .collect();
        paths.sort();
        for p in paths {
            let text = std::fs::read_to_string(&p).map_err(|e| io(e, &p))?;
            let def = parse_part(&text, &p.display().to_string())?;
            let stem = p.file_stem().and_then(|s| s.to_str()).unwrap_or_default();
            if stem != def.id.0 {
                return Err(PartsError::Invalid {
                    id: def.id.0,
                    problem: format!("file name {stem}.ron does not match the id"),
                });
            }
            parts.insert(def.id.clone(), def);
        }
        Ok(Self { parts })
    }

    /// A part by id.
    pub fn get(&self, id: &str) -> Option<&PartDef> {
        self.parts.get(&PartId(id.into()))
    }

    /// All parts in id order.
    pub fn iter(&self) -> impl Iterator<Item = &PartDef> {
        self.parts.values()
    }

    /// Number of parts.
    pub fn len(&self) -> usize {
        self.parts.len()
    }

    /// True when there are no parts.
    pub fn is_empty(&self) -> bool {
        self.parts.is_empty()
    }
}

/// Write every built-in part to `dir` as `<id>.ron`.
pub fn write_builtin(dir: &Path) -> std::io::Result<usize> {
    std::fs::create_dir_all(dir)?;
    let parts = crate::generate::builtin_parts();
    for p in &parts {
        std::fs::write(dir.join(format!("{}.ron", p.id.0)), to_ron(p))?;
    }
    Ok(parts.len())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ron_round_trip_of_every_builtin_part() {
        for p in crate::generate::builtin_parts() {
            let text = to_ron(&p);
            let back = parse_part(&text, &p.id.0).unwrap_or_else(|e| panic!("{e}"));
            assert_eq!(back, p, "{}", p.id.0);
        }
    }

    #[test]
    fn newer_files_are_refused() {
        let p = crate::generate::builtin_parts().remove(0);
        let text = to_ron(&p).replace("version: 1", "version: 2");
        assert!(matches!(parse_part(&text, "x"), Err(PartsError::TooNew)));
    }

    #[test]
    fn garbage_is_an_error_not_a_panic() {
        assert!(matches!(
            parse_part("(nope", "x"),
            Err(PartsError::Parse { .. })
        ));
    }

    #[test]
    fn a_zero_mass_is_rejected() {
        let mut p = crate::generate::builtin_parts().remove(0);
        p.bodies[0].mass_kg = 0.0;
        assert!(matches!(check(&p), Err(PartsError::Invalid { .. })));
    }
}
